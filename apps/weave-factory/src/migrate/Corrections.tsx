// "Correct the analysis": the analysis of this API as an Excel workbook. A person corrects the rows
// that are wrong and uploads it; the migration tool keeps the corrections and writes the documents
// and the project again with them. Every correction is listed in the documents.
import { useRef, useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { Download, Upload } from "lucide-react";
import { correctionsWorkbook, uploadCorrections, type ApiError, type CorrectionChange, type CorrectionCounts, type CorrectionRowError, type CorrectionsResult, type Migration } from "../api.ts";
import { txt } from "../lib/text.ts";
import { ago, dateTime } from "../lib/migrate.ts";
import { Bar, Btn, Notice, Panel, Pill, errText } from "./ui.tsx";

const KINDS: (keyof CorrectionCounts)[] = ["changed", "added", "deleted", "marked"];

export function countsText(c: Partial<CorrectionCounts> | undefined | null): string {
  const parts = KINDS.filter((k) => Number(c?.[k] ?? 0) > 0).map((k) => `${Number(c?.[k])} ${k}`);
  return parts.length ? parts.join(", ") : "no rows changed";
}

/** Shown once the documents exist; never for a package generated by Weave (it was only checked). */
export function correctable(m: Migration): boolean {
  // a service built from requirements is corrected with its requirements workbook (Requirements panel)
  return !!m.apiName && !m.checkOnly && m.sourceType !== "requirements";
}

function Changes({ list }: { list: CorrectionChange[] }) {
  if (!list.length) return null;
  return (
    <ul className="mf-mg-small mf-mg-wrap" data-testid="corrections-changes" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.5 }}>
      {list.map((c, i) => (
        <li key={i}><strong>{txt(c.sheet) || "Row"}{txt(c.id) ? <> <span className="mf-mono">{txt(c.id)}</span></> : null}</strong> · {txt(c.action)}{txt(c.summary) ? <>: {txt(c.summary)}</> : null}</li>
      ))}
    </ul>
  );
}

function RowErrors({ list }: { list: CorrectionRowError[] }) {
  return (
    <ul className="mf-mg-small mf-mg-wrap" data-testid="corrections-errors" style={{ margin: "6px 0 0", paddingLeft: 18, lineHeight: 1.5 }}>
      {list.map((e, i) => (
        <li key={i}>{txt(e.sheet) ? <>Sheet <strong>{txt(e.sheet)}</strong></> : "The workbook"}{e.row !== undefined && e.row !== "" && e.row !== null ? <>, row <strong>{String(e.row)}</strong></> : null}: {txt(e.problem)}</li>
      ))}
    </ul>
  );
}

export function Corrections({ m }: { m: Migration }) {
  const qc = useQueryClient();
  const input = useRef<HTMLInputElement>(null);
  const [file, setFile] = useState<File | null>(null);
  const [pct, setPct] = useState<number | null>(null);
  const [err, setErr] = useState<{ text: string; rows: CorrectionRowError[] } | null>(null);
  const [done, setDone] = useState<CorrectionsResult | null>(null);
  const [getting, setGetting] = useState(false);
  const [getErr, setGetErr] = useState("");
  if (!correctable(m)) return null;
  const history = [...(m.corrections ?? [])].reverse();
  const busy = !!m.busy || !!m.queued;

  // fetched first, so a refusal (no documents, a step running) is said in words instead of saving an error as a file
  const download = () => {
    setGetErr(""); setGetting(true);
    correctionsWorkbook(m.id)
      .then(({ blob, filename }) => {
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url; a.download = filename; document.body.appendChild(a); a.click(); a.remove();
        setTimeout(() => URL.revokeObjectURL(url), 30000);
      })
      .catch((e: ApiError) => setGetErr(errText(e)))
      .finally(() => setGetting(false));
  };

  const send = () => {
    if (!file) return;
    setErr(null); setDone(null); setPct(0);
    uploadCorrections(m.id, file, (f) => setPct(f)).promise
      .then((r) => {
        setPct(null); setFile(null);
        if (input.current) input.current.value = "";
        setDone(r);
        qc.invalidateQueries({ queryKey: ["migration", m.id] }); qc.invalidateQueries({ queryKey: ["migrations"] });
        qc.invalidateQueries({ queryKey: ["migration-docs", m.id] }); qc.invalidateQueries({ queryKey: ["migration-feedback", m.id] });
      })
      .catch((e: ApiError) => {
        setPct(null);
        const rows = Array.isArray(e.body?.errors) ? (e.body!.errors as CorrectionRowError[]) : [];
        setErr({ text: e.status === 409 ? errText(e) || "A step of this migration is running. Upload the corrections when it has finished." : errText(e), rows });
      });
  };

  return (
    <Panel title="Correct the analysis" actions={history.length ? <Pill tone="accent">{history.length} correction{history.length === 1 ? "" : "s"} so far</Pill> : undefined}>
      <div className="mf-mg-stack" style={{ gap: 12 }} data-testid="corrections">
        <p className="mf-mg-sub mf-mg-wrap" style={{ fontSize: 13.5, margin: 0 }}>
          Something in the documents is wrong? Correct it in a workbook and the tool writes everything again with your corrections.
        </p>
        <ol className="mf-mg-small mf-mg-wrap" style={{ margin: 0, paddingLeft: 20, lineHeight: 1.6 }} data-testid="corrections-how">
          <li>Download the workbook. It has one sheet for each part of the analysis (operations, fields, backends, flows and more).</li>
          <li>Change the rows that are wrong: set <strong>Action</strong> to <span className="mf-mono">change</span>, <span className="mf-mono">delete</span> or <span className="mf-mono">add</span> (or <span className="mf-mono">live</span> / <span className="mf-mono">dead</span> for a part that is or is not used any more), and add a note that says why.</li>
          <li>Upload it. The documents and the project are generated again with your corrections, and every correction is listed in the documents.</li>
        </ol>
        <div className="mf-mg-actions">
          <Btn data-testid="corrections-download" icon={<Download size={15} aria-hidden="true" />} disabled={busy} busy={getting} onClick={download}>Download the workbook (.xlsx)</Btn>
        </div>
        {getErr && <Notice tone="bad"><span data-testid="corrections-download-error">{getErr}</span></Notice>}
        <div className="mf-mg-row" style={{ gap: 8 }}>
          <input ref={input} type="file" accept=".xlsx,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" data-testid="corrections-file" aria-label="Corrected workbook (.xlsx)"
            onChange={(e) => { setFile(e.target.files?.[0] ?? null); setErr(null); setDone(null); }} style={{ maxWidth: "100%", minWidth: 0 }} />
          <Btn small kind="primary" data-testid="corrections-upload" icon={<Upload size={14} aria-hidden="true" />} disabled={!file || pct !== null || busy} busy={pct !== null} onClick={send}>Upload the corrections</Btn>
        </div>
        {busy && <span className="mf-mg-hint mf-mg-wrap" data-testid="corrections-busy">A step of this migration is running. The workbook can be downloaded and uploaded when it has finished.</span>}
        {pct !== null && <Bar pct={Math.round(pct * 100)} label="Upload progress" />}
        {err && (
          <Notice tone={err.rows.length ? "warn" : "bad"}>
            <span data-testid="corrections-error">{err.text}</span>
            {err.rows.length > 0 && <RowErrors list={err.rows} />}
          </Notice>
        )}
        {done && (
          <Notice tone="ok">
            <span className="mf-mg-stack" style={{ gap: 6 }} data-testid="corrections-done">
              <span>{txt(done.message) || (done.rerun ? "Corrections kept. The documents and the project are being generated again." : "No corrections were found in the workbook.")}</span>
              <span className="mf-mg-small" data-testid="corrections-counts">{countsText(done.applied)}</span>
              <Changes list={done.changes ?? []} />
            </span>
          </Notice>
        )}
        {history.length > 0 && (
          <div className="mf-mg-sec" data-testid="corrections-history">
            <h3>Earlier corrections</h3>
            <div className="mf-mg-list">
              {history.map((h, i) => (
                <div key={`${txt(h.at)}-${i}`} className="mf-mg-item"><div className="mf-mg-item-head" style={{ cursor: "default", flexWrap: "wrap" }}>
                  <span className="mf-mg-item-title mf-mg-small" title={dateTime(h.at)}>{dateTime(h.at) || "Earlier"}{h.at ? <span className="mf-mg-muted"> ({ago(h.at)})</span> : null}{txt(h.by) ? <span className="mf-mg-muted"> · {txt(h.by)}</span> : null}</span>
                  <span className="mf-mg-small mf-mg-muted mf-mg-wrap">{countsText(h.applied)}</span>
                </div></div>
              ))}
            </div>
          </div>
        )}
      </div>
    </Panel>
  );
}
